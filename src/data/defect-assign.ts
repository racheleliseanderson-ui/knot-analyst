export function isBoilerplateDefectLabel(label: string): boolean {
  return BOILERPLATE_LABELS.has(label);
}

export function overlayKeys(): Array<{ knotId: string; key: string }> {
  return Object.entries(DEFECT_OVERLAY).flatMap(([knotId, rows]) =>
    rows.map((r) => ({ knotId, key: r.key })),
  );
}

export function applyDefectOverlay(knotId: string, m: MechanicsBundle): MechanicsBundle {
  const rows = DEFECT_OVERLAY[knotId];
  if (!rows?.length) return m;
  const byKey = new Map(rows.map((r) => [r.key, r]));
  const dangerousDefects: DefectDef[] = m.fingerprint.dangerousDefects.map((d) => {
    const o = byKey.get(d.observationKey);
    if (!o) return d;
    return {
      ...d,
      label: o.label,
      consequence: o.consequence,
      mechanicsWhy: o.why,
      stepWhere: o.step ?? d.stepWhere,
    };
  });
  const observations: ObservationDef[] = m.observations.map((obs) => {
    const o = byKey.get(obs.key);
    if (!o || !obs.badWhen) return obs;
    return { ...obs, label: o.label };
  });
  return {
    ...m,
    fingerprint: { ...m.fingerprint, dangerousDefects },
    observations,
  };
}
